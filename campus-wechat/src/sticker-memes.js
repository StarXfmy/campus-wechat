function hintFor(text) {
  let rest = String(text || '');
  if (!rest) return '';
  const hits = [];
  // 长词优先：「木鱼」命中后就不再把它算成「鱼」，「螃蟹」不再算成「蟹」
  const keys = Object.keys(MEMES).sort((a, b) => b.length - a.length);
  for (const key of keys) {
    if (!rest.includes(key)) continue;
    rest = rest.split(key).join(' ');
    const meaning = MEMES[key];
    if (!hits.includes(meaning)) hits.push(meaning);
    if (hits.length >= 4) break;
  }
  return hits.length ? `【梗】${hits.join('；')}` : '';
}

